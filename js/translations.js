/**
 * Translation Manager helper
 */
window.currentLanguage = localStorage.getItem('quran_lang') || 'es';

window.setLanguage = function(lang) {
    if (!window.TRANSLATIONS[lang]) return;
    window.currentLanguage = lang;
    localStorage.setItem('quran_lang', lang);

    const dict = window.TRANSLATIONS[lang];

    // Update all elements with data-i18n attribute
    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n');
        if (dict[key]) {
            el.innerHTML = dict[key];
        }
    });

    // Update placeholders
    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
        const key = el.getAttribute('data-i18n-placeholder');
        if (dict[key]) {
            el.setAttribute('placeholder', dict[key]);
        }
    });

    // Update language toggle button states
    document.querySelectorAll('.lang-btn').forEach(btn => {
        const btnLang = btn.getAttribute('data-lang');
        if (btnLang === lang) {
            btn.classList.add('bg-amber-400', 'text-slate-950', 'font-bold');
            btn.classList.remove('text-slate-400', 'hover:text-white');
        } else {
            btn.classList.remove('bg-amber-400', 'text-slate-950', 'font-bold');
            btn.classList.add('text-slate-400', 'hover:text-white');
        }
    });

    // Update HTML lang attribute
    document.documentElement.setAttribute('lang', lang);
};
